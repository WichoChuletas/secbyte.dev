import { readdirSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const articlesDir = join(__dirname, '..', 'src', 'content', 'articles');
const outDir = join(__dirname, '..', 'src', 'generated');
const outFile = join(outDir, 'article-slugs.js');

const slugs = readdirSync(articlesDir)
	.filter((file) => file.endsWith('.md'))
	.map((file) => file.replace(/\.md$/, ''));

mkdirSync(outDir, { recursive: true });
writeFileSync(
	outFile,
	`// Generated by scripts/generate-article-slugs.mjs — do not edit by hand.\nexport const ARTICLE_SLUGS = ${JSON.stringify(slugs, null, 2)};\n`
);

console.log(`Generated ${outFile} with ${slugs.length} slug(s).`);
